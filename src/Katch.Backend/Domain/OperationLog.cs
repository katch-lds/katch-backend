using Katch.Backend.Domain.Enums;

namespace Katch.Backend.Domain;

/// <summary>
/// Linha do registo de autoria das operações sobre Empresas, vagas, contas e listas (tabela <c>operation_log</c>, RF112):
/// quem fez o quê, sobre que entidade e quando.
/// </summary>
/// <remarks>
/// O registo só admite inserções: não há métodos que alterem a linha (modelo de classes do backend v02, secção 3.4). O
/// tipo da entidade não é guardado, porque resulta de <see cref="Operation"/> (DM-19). O autor só pode faltar quando a
/// operação é <see cref="OperationType.JobClosed"/>, feita pela tarefa periódica, o que corresponde ao <c>CHECK</c>
/// <c>ck_operation_log_author</c>. O identificador é gerado pela base de dados.
/// </remarks>
public sealed class OperationLog
{
    private OperationLog(Guid? userId, OperationType operation, Guid entityId, DateTimeOffset now)
    {
        if (userId == Guid.Empty)
        {
            throw new ArgumentException("O identificador do autor, quando existe, não pode estar vazio.", nameof(userId));
        }

        if (!Enum.IsDefined(operation))
        {
            throw new ArgumentException("A operação não pertence à lista (RF112).", nameof(operation));
        }

        if (entityId == Guid.Empty)
        {
            throw new ArgumentException("O identificador da entidade é obrigatório.", nameof(entityId));
        }

        if (userId is null && operation != OperationType.JobClosed)
        {
            throw new ArgumentException(
                "Só o encerramento automático de uma vaga pode ficar sem autor.",
                nameof(userId));
        }

        this.UserId = userId;
        this.Operation = operation;
        this.EntityId = entityId;
        this.OccurredAt = now;
    }

    /// <summary>
    /// Initializes a new instance of the <see cref="OperationLog"/> class. Usado pelo Entity Framework Core.
    /// </summary>
    private OperationLog()
    {
    }

    /// <summary>
    /// Gets the identifier of the line (<c>id</c>), generated by the database; zero until the line is saved.
    /// </summary>
    public long Id { get; private set; }

    /// <summary>
    /// Gets the identifier of the account that did the operation (<c>user_id</c>); empty only for
    /// <see cref="OperationType.JobClosed"/> done by the periodic task.
    /// </summary>
    public Guid? UserId { get; private set; }

    /// <summary>
    /// Gets the operation that was done (<c>operation</c>).
    /// </summary>
    public OperationType Operation { get; private set; }

    /// <summary>
    /// Gets the identifier of the entity the operation was done on (<c>entity_id</c>); the type of the entity results
    /// from <see cref="Operation"/> (DM-19).
    /// </summary>
    public Guid EntityId { get; private set; }

    /// <summary>
    /// Gets the instant in which the operation was done (<c>occurred_at</c>).
    /// </summary>
    public DateTimeOffset OccurredAt { get; private set; }

    /// <summary>
    /// Cria a linha de registo de uma operação.
    /// </summary>
    /// <param name="userId">
    /// Identificador da conta que fez a operação; pode faltar apenas com <see cref="OperationType.JobClosed"/>.
    /// </param>
    /// <param name="operation">Operação feita.</param>
    /// <param name="entityId">Identificador da entidade sobre a qual foi feita.</param>
    /// <param name="now">Instante da operação, em UTC.</param>
    /// <returns>A nova linha de registo.</returns>
    /// <exception cref="ArgumentException">
    /// Se algum dos identificadores estiver vazio, se a operação não pertencer à enumeração ou se faltar o autor numa
    /// operação diferente de <see cref="OperationType.JobClosed"/>.
    /// </exception>
    public static OperationLog Record(Guid? userId, OperationType operation, Guid entityId, DateTimeOffset now)
    {
        return new OperationLog(userId, operation, entityId, now);
    }
}
